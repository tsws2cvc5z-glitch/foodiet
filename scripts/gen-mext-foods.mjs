// 検索で上に出したい定番の食品（前ほど上）
const POPULAR = [
  1088, 12004, 1026, 13003, 4046, 7107, 4032, 4033, 1039, 1128, 1048, 1064, 1111, 1004, 13025,
  11220, 11221, 11186, 11176, 11183, 10139, 10134, 6182, 6061, 6263, 7148, 7027, 16006, 16045,
];

const round1 = (n) => Math.round(n * 10) / 10;
const num = (...vals) => {
  for (const v of vals) if (typeof v === 'number') return v;
  return 0; // 'Tr' や '-' は null になっているので 0 とみなす
};
const cleanName = (s) =>
  s.replace(/〕/g, ']').replace(/\s+/g, ' ').trim();

const data = JSON.parse(readFileSync(src, 'utf8'));
const foods = data.map((x) => {
  const name = cleanName(x.foodName);
  const aliases = ALIASES.filter(([key]) => name.includes(key)).map(([, a]) => a);
  return [
    x.foodId,
    name,
    num(x.enercKcal),
    round1(num(x.prot, x.protcaa)),
    round1(num(x.fat, x.fatnlea)),
    round1(num(x.chocdf, x.choavldf)),
    aliases.join(' '),
  ];
});

const ids = new Set(foods.map((f) => f[0]));
for (const id of [...Object.keys(SERVINGS), ...POPULAR]) {
  if (!ids.has(Number(id))) throw new Error(`SERVINGS/POPULAR: 食品番号 ${id} が見つかりません`);
}

const out = {
  source: '日本食品標準成分表2020年版（八訂）（文部科学省）',
  foods,
  servings: SERVINGS,
  popular: POPULAR,
};
writeFileSync('public/foods-mext.json', JSON.stringify(out));
console.log(`wrote ${foods.length} foods to public/foods-mext.json`);
